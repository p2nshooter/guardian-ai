export const LIBRARY: Record<FrameworkId, FrameworkControls> = { iso27001: ISO, soc2: SOC2, nist: NIST, pci: PCI, hipaa: HIPAA, gdpr: GDPR, uupdp: UUPDP };
export const controlsOf = (fw: FrameworkId) => LIBRARY[fw].controls;
export const findControl = (fw: FrameworkId, id: string) => LIBRARY[fw].controls.find((c) => c.id === id);
export const controlKey = (fw: FrameworkId, id: string) => `${fw}:${id}`;
export const TOTAL_CONTROLS = Object.values(LIBRARY).reduce((n, f) => n + f.controls.length, 0);

/** Controls in OTHER frameworks that share at least `min` themes with this one, best first. */
export function mappedControls(fw: FrameworkId, id: string, min = 1): { fw: FrameworkId; control: Control; shared: Theme[] }[] {
  const me = findControl(fw, id);
  if (!me) return [];
  const out: { fw: FrameworkId; control: Control; shared: Theme[] }[] = [];
  for (const [f, lib] of Object.entries(LIBRARY) as [FrameworkId, FrameworkControls][]) {
    if (f === fw) continue;
    for (const c of lib.controls) {
      // The primary (first) theme must match: keeps mappings meaningful, not just "both mention policy".
      const shared = c.themes.filter((t) => me.themes.includes(t));
      if (shared.length >= min && (me.themes[0] === c.themes[0] || shared.length >= 2)) out.push({ fw: f, control: c, shared });
    }
  }
  return out.sort((a, b) => b.shared.length - a.shared.length);
}
